#!/bin/bash
# vendor_whisper.sh — 把 whisper.cpp 固定版本克隆进 Sources/CWhisper（只拷编译所需）
# 用法: bash scripts/vendor_whisper.sh [tag]
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"
TAG="${1:-v1.9.5}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "▶ 克隆 whisper.cpp $TAG ..."
git clone --quiet --depth 1 --branch "$TAG" https://github.com/ggml-org/whisper.cpp "$TMP/w"

DEST="$ROOT/Sources/CWhisper"
rm -rf "$DEST"
mkdir -p "$DEST/include" "$DEST/src" "$DEST/ggml"

# 公开头文件：whisper.h + ggml 全部头（SPM 对 C/C++ target 自动公开 include/）
cp "$TMP/w/include/"*.h "$DEST/include/"
cp "$TMP/w/ggml/include/"*.h "$DEST/include/" 2>/dev/null || true

# 源码（递归，包含 aneforge 等子目录；剔除 CMake 文件）
cp -R "$TMP/w/src/." "$DEST/src/"
find "$DEST/src" -name CMakeLists.txt -delete
cp -R "$TMP/w/ggml/src/." "$DEST/ggml/"

# C++-only 头不能留在公开 include/（WhisperBridge 以纯 C 编译模块，<memory> 会炸）
mv -f "$DEST/include/ggml-cpp.h" "$DEST/ggml/" 2>/dev/null || true
mv -f "$DEST/include/ggml-openvino.h" "$DEST/ggml/" 2>/dev/null || true

# 生成 ggml-version.h（CMake 会做这事，这里手工等价生成）
VERSION="${TAG#v}"
BUILD_COMMIT="$(git -C "$TMP/w" rev-parse --short HEAD 2>/dev/null || echo unknown)"
cat > "$DEST/include/ggml-version.h" <<EOF
#pragma once
// generated by vendor_whisper.sh — do not edit
#define GGML_VERSION "${VERSION}"
#define GGML_COMMIT  "${BUILD_COMMIT}"
EOF

# 预编译 Metal kernels → default.metallib（需要 Xcode 的 metal 工具链；CLT 里没有）
# ggml 运行时在 SWIFTPM_MODULE_BUNDLE 里查找 default.metallib，该文件由 SPM resources 分发。
export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"
STAGE="$(mktemp -d)"
trap 'rm -rf "$TMP" "$STAGE"' EXIT
cp "$DEST/ggml/ggml-common.h" "$STAGE/"
cp "$DEST/ggml/ggml-metal/ggml-metal-impl.h" "$STAGE/"
mkdir -p "$STAGE/kernels" "$DEST/Resources"
cp "$DEST/ggml/ggml-metal/kernels/"* "$STAGE/kernels/"
AIRS=()
for f in "$STAGE/kernels/"*.metal; do
  base="$(basename "${f%.metal}")"
  case "$base" in fa_common|fa_vec_common) continue;; esac   # 共享头，仅被 include
  air="$STAGE/$base.air"
  xcrun -sdk macosx metal -O3 -I "$STAGE" -c "$f" -o "$air" || { echo "✗ metal 编译失败: $base"; exit 1; }
  AIRS+=("$air")
done
xcrun -sdk macosx metallib "${AIRS[@]}" -o "$DEST/Resources/default.metallib"
echo "✓ default.metallib 编译完成 ($(du -h "$DEST/Resources/default.metallib" | cut -f1), ${#AIRS[@]} kernels)"

# 运行时源码编译回退所需的资源（metallib 加载失败时 ggml 用 GGML_METAL_PATH_RESOURCES 找源码）
mkdir -p "$DEST/Resources/kernels"
cp "$DEST/ggml/ggml-metal/kernels/"* "$DEST/Resources/kernels/"
cp "$DEST/ggml/ggml-common.h" "$DEST/Resources/"
cp "$DEST/ggml/ggml-metal/ggml-metal-impl.h" "$DEST/Resources/"

echo "✓ 已拷贝。关键文件:"
find "$DEST" -maxdepth 4 \( -name "whisper.cpp" -o -name "whisper.h" -o -name "ggml-metal.m" -o -name "*.metal" \) | sed 's/^/  /'
echo "— src/:"; ls "$DEST/src"
echo "— ggml/ 顶层:"; ls "$DEST/ggml"
