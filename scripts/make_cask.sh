#!/bin/bash
# make_cask.sh — 生成 Homebrew Cask（发布到 etng/homebrew-taps 用）
# 用法: bash scripts/make_cask.sh <version> <dmg路径> [owner/repo] [输出路径]
# 例:   bash scripts/make_cask.sh 0.1.0 dist/SubNow-0.1.0.dmg etng/subnow dist/subnow.rb
set -euo pipefail
cd "$(dirname "$0")/.."

VERSION="${1:?需要版本号，例如 0.1.0}"
DMG="${2:?需要 DMG 路径}"
REPO="${3:-}"
OUT="${4:-dist/subnow.rb}"

if [ ! -f "$DMG" ]; then
    echo "✗ 找不到 DMG: $DMG"
    exit 1
fi
if ! [[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "✗ 版本号不是 X.Y.Z: $VERSION"
    exit 1
fi
if [ -z "$REPO" ]; then
    REPO="$(git config --get remote.origin.url 2>/dev/null \
        | sed -E 's#^(git@github.com:|https://github.com/)##; s#\.git$##')" || true
fi
if ! [[ "$REPO" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
    echo "✗ 无法确定 GitHub 仓库，请传入 owner/repo"
    exit 1
fi

SHA="$(shasum -a 256 "$DMG" | awk '{print $1}')"
mkdir -p "$(dirname "$OUT")"

cat > "$OUT" <<RUBY
# typed: strict
# frozen_string_literal: true

# This file was generated by the SubNow release workflow. DO NOT EDIT.
#
# 源模板: https://github.com/${REPO} → scripts/make_cask.sh
# 每次在 ${REPO} 打 v* tag 时，发布流水线会重新生成本文件并推送到本仓库。
cask "subnow" do
  version "${VERSION}"
  sha256 "${SHA}"

  url "https://github.com/${REPO}/releases/download/v#{version}/SubNow-#{version}.dmg"
  name "SubNow"
  desc "Menu bar subtitle generator for mpv and IINA"
  homepage "https://github.com/${REPO}"

  livecheck do
    skip "Auto-generated on release."
  end

  depends_on arch: :arm64
  depends_on macos: ">= :sonoma"

  app "SubNow.app"

  # 应用未做 Apple 公证（ad-hoc 签名）。下载后会被打上隔离标记，
  # 不去掉的话首次打开会被 Gatekeeper 拦下报「已损坏」。
  # 路径必须用 {{appdir}} 模板：steps 块在独立 DSL 上求值，拿不到 cask 的 appdir 方法；
  # 也不能写 postflight，Homebrew 7 已废弃它（改用 *_steps + 规范化步骤）。
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/SubNow.app"]
  end

  zap trash: [
    "~/Library/Application Support/SubNow",
    "~/Library/Logs/SubNow.log",
    "~/Library/Preferences/com.y10n.subnow.plist",
    "~/Library/Saved Application State/com.y10n.subnow.savedState",
  ]

  caveats <<~EOS
    SubNow 未做 Apple 公证（ad-hoc 签名），安装时已自动清除隔离标记。
    若打开时仍提示「已损坏」，请手动执行：
      xattr -dr com.apple.quarantine /Applications/SubNow.app

    首次启动会引导下载 whisper 模型；模型与配置保存在
    ~/Library/Application Support/SubNow。
  EOS
end
RUBY

echo "✓ Cask: ${OUT}（sha256 ${SHA}）"
